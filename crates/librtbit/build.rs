use anyhow::{Context, bail};
use std::path::Path;
use std::process::Command;
use std::thread;
use std::time::Duration;

#[allow(dead_code)]
fn run_cmd(cwd: &Path, cmd: &str) -> anyhow::Result<()> {
    #[cfg(target_os = "windows")]
    let (shell, shell_args) = ("powershell", ["-command"].as_slice());
    #[cfg(not(target_os = "windows"))]
    let (shell, shell_args) = ("sh", ["-c"].as_slice());

    // Run "npm install" in the webui directory
    let output = Command::new(shell)
        .args(shell_args)
        .arg(cmd)
        .current_dir(cwd)
        .output()
        .with_context(|| {
            format!(
                "Failed to execute {} in {:?}. PATH: {:?}",
                cmd,
                cwd,
                std::env::var("PATH").unwrap_or_default()
            )
        })?;

    if !output.status.success() {
        bail!(
            "\"{}\" failed\n\nstderr: {}\n\nstdout: {}",
            cmd,
            String::from_utf8_lossy(&output.stderr),
            String::from_utf8_lossy(&output.stdout)
        );
    }

    // Optionally print the stdout output if you want to see the build logs
    println!("{}", String::from_utf8_lossy(&output.stdout));

    Ok(())
}

#[allow(dead_code)]
fn run_cmd_with_retry(cwd: &Path, cmd: &str, attempts: usize) -> anyhow::Result<()> {
    let mut last_error = None;

    for attempt in 1..=attempts {
        match run_cmd(cwd, cmd) {
            Ok(()) => return Ok(()),
            Err(error) if attempt < attempts => {
                println!("cargo:warning={cmd} attempt {attempt}/{attempts} failed; retrying");
                last_error = Some(error);
                thread::sleep(Duration::from_secs(5 * attempt as u64));
            }
            Err(error) => return Err(error),
        }
    }

    Err(last_error.expect("attempts must be greater than zero"))
}

fn main() {
    #[cfg(feature = "webui")]
    {
        let webui_dir = Path::new("webui");
        let webui_src_dir = webui_dir.join("src");

        println!("cargo:rerun-if-changed={}", webui_src_dir.to_str().unwrap());

        // Registry connections can reset during slow cross-architecture
        // container builds. Retry only the network-dependent install step;
        // keep the deterministic build command fail-fast.
        run_cmd_with_retry(webui_dir, "npm ci --no-audit --no-fund", 3).unwrap();
        run_cmd(webui_dir, "npm run build").unwrap();
        write_asset_manifest(&webui_dir.join("dist")).unwrap();
    }
}

/// Emit `$OUT_DIR/webui_assets.rs`: every file under `dist/` (entry files,
/// hashed lazy chunks and nested paths alike) as an `include_bytes!` table
/// the router serves. The generated file lives in `$OUT_DIR`, never the
/// source tree; `include_bytes!` paths are absolute.
#[cfg(feature = "webui")]
fn write_asset_manifest(dist: &Path) -> anyhow::Result<()> {
    let manifest_dir =
        Path::new(&std::env::var("CARGO_MANIFEST_DIR").context("CARGO_MANIFEST_DIR")?)
            .canonicalize()
            .context("canonicalize manifest dir")?;
    let mut entries: Vec<(String, String)> = Vec::new();
    collect_assets(dist, dist, &manifest_dir, &mut entries)?;
    entries.sort();

    let mut source = String::from(
        "// Generated by build.rs. Do not edit.\n\
         pub struct WebuiAsset {\n\
         \tpub path: &'static str,\n\
         \tpub bytes: &'static [u8],\n\
         \tpub content_type: &'static str,\n\
         }\n\
         \n\
         pub static WEBUI_ASSETS: &[WebuiAsset] = &[\n",
    );
    for (rel, include_path) in &entries {
        let content_type = content_type_for(rel);
        source.push_str(&format!(
            "\tWebuiAsset {{ path: {rel:?}, bytes: include_bytes!({include_path:?}), content_type: {content_type:?} }},\n"
        ));
    }
    source.push_str("];\n");
    let out_dir = std::env::var("OUT_DIR").context("OUT_DIR")?;
    let dest = Path::new(&out_dir).join("webui_assets.rs");
    std::fs::write(&dest, source).with_context(|| format!("write {dest:?}"))?;
    Ok(())
}

#[cfg(feature = "webui")]
fn collect_assets(
    dist: &Path,
    dir: &Path,
    manifest_dir: &Path,
    out: &mut Vec<(String, String)>,
) -> anyhow::Result<()> {
    for entry in std::fs::read_dir(dir).with_context(|| format!("read {dir:?}"))? {
        let entry = entry?;
        let path = entry.path();
        if path.is_dir() {
            // Vite's build manifest is a build input, not a served asset.
            if path.file_name().is_some_and(|name| name == ".vite") {
                continue;
            }
            collect_assets(dist, &path, manifest_dir, out)?;
        } else if path.is_file() {
            let canonical = path
                .canonicalize()
                .with_context(|| format!("canonicalize {path:?}"))?;
            let rel = path
                .strip_prefix(dist)
                .unwrap()
                .to_str()
                .context("non-utf8 asset path")?
                .replace('\\', "/");
            // The generated module is included from $OUT_DIR, so include_bytes!
            // must be an absolute path. Only files inside the crate are embedded.
            canonical
                .strip_prefix(manifest_dir)
                .with_context(|| format!("{canonical:?} is outside {manifest_dir:?}"))?;
            let include = canonical
                .to_str()
                .context("non-utf8 asset path")?
                .replace('\\', "/");
            println!("cargo:rerun-if-changed={}", path.display());
            out.push((rel, include));
        }
    }
    Ok(())
}

#[cfg(feature = "webui")]
fn content_type_for(path: &str) -> &'static str {
    match Path::new(path).extension().and_then(|ext| ext.to_str()) {
        Some("html") => "text/html",
        Some("js" | "mjs") => "text/javascript",
        Some("css") => "text/css",
        Some("svg") => "image/svg+xml",
        Some("json") => "application/json",
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("gif") => "image/gif",
        Some("webp") => "image/webp",
        Some("ico") => "image/x-icon",
        Some("woff2") => "font/woff2",
        Some("woff") => "font/woff",
        Some("ttf") => "font/ttf",
        Some("map") => "application/json",
        Some("txt") => "text/plain",
        _ => "application/octet-stream",
    }
}
